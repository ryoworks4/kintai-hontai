  /** 待ちの帯の文とボタン。様子ごとに、押してよいボタンだけを出す */
  function 帯を描く() {
    var 帯 = 要素('待ちの知らせ'), 文 = 要素('待ちの文'), ボタン = 要素('待ちのボタン');
    var 打刻の待ち = !!待ち && !送っている && 待ちの様子 !== '照会中' && 待ちの様子 !== '取り消し中';
    // 前の登録の日報の待ち（端末が止められて登録し直した）。届いたか分からないので黙って消さず、代表に伝えてもらう（2026-10-29 Codex ③ 2回目）
    var 前の日報 = !!日報の待ち && 日報の待ち.鍵 !== 鍵 && !!鍵;
    帯.hidden = !打刻の待ち && !前の日報;
    ボタン.textContent = '';
    if (帯.hidden) return;
    var 置く = function (名前, 控えめ, 押したら) {
      var b = 作る('button', { type: 'button', class: 'btn' + (控えめ ? ' ghost' : ''), text: 名前 });
      b.addEventListener('click', 押したら);
      ボタン.appendChild(b);
    };
    if (!打刻の待ち) {
      文.textContent = '前の登録で送った ' + 日付の表示(日報の待ち.日付) + ' の日報（休憩 ' + 日報の待ち.休憩分 + '分' +
          (日報の待ち.理由 ? '・' + 日報の待ち.理由 : '') + '）が、記録されたか確認できないまま残っています。この端末では送れないので、代表に伝えてください。';
      置く('消す', true, function () { 日報の待ち = null; しまう('日報の待ち', null); 描く(); });
      return;
    }
    var いつ = 端末の時分(待ち.押した) + ' に押した「' + 待ち.種類 + '」';
    if (待ちの様子 === '別の登録') {
      文.textContent = '前の登録で ' + いつ + 'が残っています。この端末では送れないので、代表に伝えてください。';
      置く('消す', true, 待ちを消す);
    } else if (待ちの様子 === '届いていない') {
      文.textContent = いつ + 'は、届いていませんでした。';
      置く('いまの時刻で記録する', false, 送り続ける);
      置く('記録しない', true, 取り消す);
    } else {
      文.textContent = いつ + 'が、記録されたか確認できません。電波のよい所で「もう一度送る」を押してください（二重にはなりません）。';
      置く('もう一度送る', false, 送り続ける);
    }
  }

  function 描く() {
    var 今 = 今の分(), 今日 = 今日の日付();
    var 最後の = function (種類たち) {
      return 記録.filter(function (r) { return 種類たち.indexOf(r.種類) >= 0; })[0] || null;
    };
    var 前から = function (r) { return r ? 今 - 分に(r.時刻) : Infinity; };
    // 勤務中・呼び出し中は、日付ではなく最後の記録で決める（0時をまたいでも退勤・帰着を押せるように）
    var 最後の勤務 = 最後の(['出勤', '退勤']), 最後の夜 = 最後の(['出発', '帰着']);
    var 勤務中 = !!最後の勤務 && 最後の勤務.種類 === '出勤' && 前から(最後の勤務) < 24 * 60;
    var 夜中 = !!最後の夜 && 最後の夜.種類 === '出発' && 前から(最後の夜) < 24 * 60;
    var 今日の出勤 = 記録.filter(function (r) { return r.種類 === '出勤' && r.時刻.slice(0, 10) === 今日; })[0];

    var 表示 = {
      出勤: 勤務中 ? 最後の勤務 : 今日の出勤,
      退勤: !勤務中 && 最後の勤務 && 最後の勤務.種類 === '退勤' && 前から(最後の勤務) < 16 * 60 ? 最後の勤務 : null,
      出発: 夜中 ? 最後の夜 : null,
      帰着: !夜中 && 最後の夜 && 最後の夜.種類 === '帰着' && 前から(最後の夜) < 12 * 60 ? 最後の夜 : null
    };
    var 押せる = { 出勤: !勤務中, 退勤: 勤務中, 出発: !夜中, 帰着: 夜中 };
    打刻の種類.forEach(function (種類) {
      var b = 要素(種類), 小 = 要素(種類 + 'の時刻');
      if (待ち && 待ち.種類 === 種類) {
        小.textContent = 端末の時分(待ち.押した) + (送っている ? ' 送っています…' : 待ちの様子 === '照会中' ? ' 確かめています…' :
            待ちの様子 === '取り消し中' ? ' 取り消しています…' : ' 未確認');
      } else {
        小.textContent = 表示[種類] ? '記録 ' + 時分(表示[種類].時刻) : (種類 === '出勤' ? '押すと時刻が残る' : '—');
      }
      b.classList.toggle('pending', !!(待ち && 待ち.種類 === 種類));
      // 待ちがある間は、どれも押せない（待ちは1つだけ）
      b.disabled = !!待ち || !押せる[種類];
    });

    // 夜の呼び出しは、勤務中でなければいつでも出す（B を 2026-10-12 に広げた：土日の日中にも呼び出しがあるため）。
    // 呼び出し中・その待ちがある時は、勤務中でも出す
    var 待ちが夜 = !!待ち && (待ち.種類 === '出発' || 待ち.種類 === '帰着');
    要素('夜').hidden = !(夜中 || 待ちが夜 || !勤務中);

    要素('状態').textContent = 状態の文;
    帯を描く();
    日報を描く();

    var 一覧 = 要素('記録');
    一覧.textContent = '';
    if (待ち) {
      var 押した日 = new Date(待ち.押した);
      一覧.appendChild(作る('li', { class: 'li pending' }, [
        作る('span', { class: 'd', text: (押した日.getMonth() + 1) + '/' + 押した日.getDate() }),
        作る('span', { text: 待ち.種類 + (送っている ? '（送信中）' : '（未確認）') }),
        作る('span', { class: 't', text: 端末の時分(待ち.押した) })
      ]));
    }
    記録.forEach(function (r) {
      一覧.appendChild(作る('li', { class: 'li' }, [
        作る('span', { class: 'd', text: 月日(r.時刻) }), 作る('span', { text: r.種類 }),
        作る('span', { class: 't', text: 時分(r.時刻) })
      ]));
    });
    if (!待ち && !記録.length) 一覧.appendChild(作る('li', { class: 'li empty', text: 'まだ記録はありません' }));
  }
